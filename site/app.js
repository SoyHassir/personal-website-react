const root = document.documentElement;
const languageButton = document.querySelector('[data-language-toggle]');
const themeButton = document.querySelector('[data-theme-toggle]');
const menuButton = document.querySelector('[data-menu-toggle]');
const mobileNav = document.querySelector('[data-mobile-nav]');
const header = document.querySelector('[data-header]');
const navLinks = [...document.querySelectorAll('[data-nav-link]')];
const mobileLinks = [...document.querySelectorAll('[data-mobile-link]')];
const sections = [...document.querySelectorAll('.section-anchor')];
const sectionTargets = {
  inicio: document.querySelector('#inicio .hero-content'),
  'sobre-mi': document.querySelector('#sobre-mi .section-heading'),
  servicios: document.querySelector('#servicios .section-heading'),
  contacto: document.querySelector('#contacto .contact-copy')
};
const sectionLinks = [...document.querySelectorAll('a[href^="#"]')].filter((link) => {
  const id = link.getAttribute('href').slice(1);
  return Boolean(sectionTargets[id]);
});

let language = localStorage.getItem('hassir-2026-language') || 'es';
const storedTheme = localStorage.getItem('hassir-2026-theme');
let theme = storedTheme || 'dark';

function lookup(key, object) {
  return key.split('.').reduce((value, part) => value?.[part], object);
}

function applyLanguage(nextLanguage) {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = lookup(element.dataset.i18n, translations[language]);
    if (value) element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = lookup(element.dataset.i18nHtml, translations[language]);
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const value = lookup(element.dataset.i18nAria, translations[language]);
    if (value) element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const value = lookup(element.dataset.i18nAlt, translations[language]);
    if (value) element.setAttribute('alt', value);
  });
  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    const value = lookup(element.dataset.i18nContent, translations[language]);
    if (value) element.setAttribute('content', value);
  });
  const localizedTitle = lookup('metadata.title', translations[language]);
  if (localizedTitle) document.title = localizedTitle;
  const emailSubjects = lookup('metadata.emailSubjects', translations[language]);
  document.querySelectorAll('[data-mailto-service]').forEach((element) => {
    const subject = emailSubjects?.[element.dataset.mailtoService];
    if (subject) element.href = `mailto:hola@hassirlastre.com?subject=${encodeURIComponent(subject)}`;
  });
  languageButton.querySelector('span:first-child').classList.toggle('active', language === 'es');
  languageButton.querySelector('span:last-child').classList.toggle('active', language === 'en');
  languageButton.setAttribute('aria-label', language === 'es' ? 'Cambiar a inglés' : 'Switch to Spanish');
  localStorage.setItem('hassir-2026-language', language);
  updateMenuLabel(menuButton.getAttribute('aria-expanded') === 'true');
  applyTheme(theme);
}

function applyTheme(nextTheme) {
  theme = nextTheme;
  root.dataset.theme = theme;
  const isLight = theme === 'light';
  themeButton.setAttribute('aria-label', isLight ? (language === 'es' ? 'Cambiar a tema oscuro' : 'Switch to dark theme') : (language === 'es' ? 'Cambiar a tema claro' : 'Switch to light theme'));
  document.querySelector('meta[name="theme-color"]').setAttribute('content', isLight ? '#edf3ff' : '#091431');
  localStorage.setItem('hassir-2026-theme', theme);
}

function updateMenuLabel(isOpen) {
  const label = isOpen ? translations[language].closeMenu : translations[language].menu;
  menuButton.querySelector('.sr-only').textContent = label;
  menuButton.setAttribute('aria-label', label);
}

function setMenuState(isOpen, { moveFocus = false } = {}) {
  menuButton.setAttribute('aria-expanded', String(isOpen));
  updateMenuLabel(isOpen);
  if (isOpen) {
    mobileNav.hidden = false;
    requestAnimationFrame(() => mobileNav.classList.add('open'));
    if (moveFocus) requestAnimationFrame(() => mobileLinks[0]?.focus());
    return;
  }
  mobileNav.classList.remove('open');
  mobileNav.hidden = true;
  if (moveFocus) menuButton.focus();
}

function closeMenu(options = {}) {
  setMenuState(false, options);
}

function scrollToSection(id, { behavior } = {}) {
  const target = sectionTargets[id];
  if (!target) return false;

  const headerOffset = header.getBoundingClientRect().height + 24;
  const top = Math.max(0, window.scrollY + target.getBoundingClientRect().top - headerOffset);
  const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  window.scrollTo({ top, behavior: behavior || (prefersReducedMotion ? 'auto' : 'smooth') });
  return true;
}

function handleSectionLink(event) {
  const id = event.currentTarget.getAttribute('href').slice(1);
  if (!sectionTargets[id]) return;
  event.preventDefault();
  if (event.currentTarget.matches('[data-mobile-link]')) closeMenu();
  if (window.location.hash !== `#${id}`) history.pushState(null, '', `#${id}`);
  scrollToSection(id);
}

languageButton.addEventListener('click', () => applyLanguage(language === 'es' ? 'en' : 'es'));
themeButton.addEventListener('click', () => applyTheme(theme === 'dark' ? 'light' : 'dark'));
menuButton.addEventListener('click', () => {
  const open = menuButton.getAttribute('aria-expanded') === 'true';
  setMenuState(!open, { moveFocus: true });
});
sectionLinks.forEach((link) => link.addEventListener('click', handleSectionLink));
document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && menuButton.getAttribute('aria-expanded') === 'true') {
    closeMenu({ moveFocus: true });
  }
});

if ('IntersectionObserver' in window) {
  root.classList.add('reveal-ready');
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        revealObserver.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll('[data-reveal]').forEach((element) => revealObserver.observe(element));

  const navObserver = new IntersectionObserver((entries) => {
    const entry = entries.filter((item) => item.isIntersecting).sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
    if (!entry) return;
    [...navLinks, ...mobileLinks].forEach((link) => {
      const isActive = link.getAttribute('href') === `#${entry.target.id}`;
      if (isActive) link.setAttribute('aria-current', 'page');
      else link.removeAttribute('aria-current');
    });
  }, { rootMargin: '-25% 0px -60% 0px', threshold: [0.1, 0.3, 0.6] });
  sections.forEach((section) => navObserver.observe(section));
}

window.addEventListener('scroll', () => header.classList.toggle('scrolled', window.scrollY > 20), { passive: true });
window.addEventListener('hashchange', () => {
  const id = window.location.hash.slice(1);
  requestAnimationFrame(() => scrollToSection(id, { behavior: 'auto' }));
});
document.querySelector('[data-year]').textContent = new Date().getFullYear();
applyLanguage(language);
applyTheme(theme);
if (window.location.hash) {
  requestAnimationFrame(() => scrollToSection(window.location.hash.slice(1), { behavior: 'auto' }));
}
